-- SUZUKA CMS setup for Supabase
-- Run this whole script in Supabase Dashboard > SQL Editor.
create table if not exists public.site_owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null default '',
  category text not null check (category in ('Nature','Travel','Adventure','Weddings','Stage Shows','Live Moments')),
  storage_path text not null,
  public_url text not null,
  media_type text not null check (media_type in ('image','video')),
  created_at timestamptz not null default now()
);
create table if not exists public.site_settings (
  id integer primary key check (id = 1),
  tagline text not null default 'Nature • Travel • Adventure • Weddings • Stage Shows',
  about_title text not null default 'Every frame tells a story.',
  about_text text not null default 'A visual storyteller capturing nature, travel, adventure, weddings and live stage shows.',
  contact_email text not null default '',
  instagram text not null default ''
);
insert into public.site_settings (id) values (1) on conflict (id) do nothing;

alter table public.site_owners enable row level security;
alter table public.gallery_items enable row level security;
alter table public.site_settings enable row level security;

-- Public can read portfolio content. Only allow-listed owner can change it.
create policy "Anyone can read gallery" on public.gallery_items for select using (true);
create policy "Owner can add gallery" on public.gallery_items for insert to authenticated with check (exists(select 1 from public.site_owners o where o.user_id = auth.uid()));
create policy "Owner can delete gallery" on public.gallery_items for delete to authenticated using (exists(select 1 from public.site_owners o where o.user_id = auth.uid()));
create policy "Anyone can read site settings" on public.site_settings for select using (true);
create policy "Owner can insert site settings" on public.site_settings for insert to authenticated with check (exists(select 1 from public.site_owners o where o.user_id = auth.uid()));
create policy "Owner can update site settings" on public.site_settings for update to authenticated using (exists(select 1 from public.site_owners o where o.user_id = auth.uid())) with check (exists(select 1 from public.site_owners o where o.user_id = auth.uid()));
create policy "Owner list readable by signed-in user" on public.site_owners for select to authenticated using (user_id = auth.uid());

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('portfolio-media','portfolio-media',true,104857600,array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public=true, file_size_limit=104857600;

create policy "Public can view portfolio media" on storage.objects for select using (bucket_id = 'portfolio-media');
create policy "Owner can upload portfolio media" on storage.objects for insert to authenticated
with check (bucket_id = 'portfolio-media' and (storage.foldername(name))[1] = auth.uid()::text and exists(select 1 from public.site_owners o where o.user_id = auth.uid()));
create policy "Owner can delete portfolio media" on storage.objects for delete to authenticated
using (bucket_id = 'portfolio-media' and (storage.foldername(name))[1] = auth.uid()::text and exists(select 1 from public.site_owners o where o.user_id = auth.uid()));

